-- Baume — système de caisse (novembre 2026)
--   1. Caisses (identifiant fixe, ex. CAISSE-GENEVE-01)
--   2. Sessions de caisse : ouverture (fond de caisse), clôture (comptage,
--      écart, rapport Z figé). Une seule session ouverte par caisse.
--   3. Mouvements d'espèces (entrées / sorties avec motif)
--   4. Remboursements et retours en boutique (fonction atomique)
--
-- Migration idempotente : peut être relancée sans erreur.
-- Prérequis : migration 20261113140000 (fonction sync_variant_inventory).
-- ═══════════════════════════════════════════════════════════════════════════

-- ── 1. Caisses ─────────────────────────────────────────────────────────────
create table if not exists public.pos_registers (
  id          uuid primary key default gen_random_uuid(),
  code        text not null unique,
  name        text not null,
  location    text,
  active      boolean not null default true,
  created_at  timestamptz not null default now()
);

insert into public.pos_registers (code, name, location)
values ('CAISSE-GENEVE-01', 'Caisse principale', 'Boutique Genève')
on conflict (code) do nothing;

-- ── 2. Sessions ────────────────────────────────────────────────────────────
create table if not exists public.pos_sessions (
  id               uuid primary key default gen_random_uuid(),
  session_number   bigint generated by default as identity,
  register_id      uuid not null references public.pos_registers(id),
  status           text not null default 'open' check (status in ('open', 'closed')),
  opened_at        timestamptz not null default now(),
  opened_by        uuid references public.profiles(id),
  opening_float    numeric(12,2) not null default 0 check (opening_float >= 0),
  opening_detail   jsonb,
  opening_note     text,
  closed_at        timestamptz,
  closed_by        uuid references public.profiles(id),
  counted_cash     numeric(12,2),
  counted_detail   jsonb,
  expected_cash    numeric(12,2),
  cash_difference  numeric(12,2),
  report           jsonb,
  closing_note     text,
  created_at       timestamptz not null default now()
);

-- Une seule session ouverte à la fois par caisse.
create unique index if not exists pos_sessions_one_open_per_register
  on public.pos_sessions (register_id) where status = 'open';
create index if not exists pos_sessions_register_opened_idx
  on public.pos_sessions (register_id, opened_at desc);

-- Une session clôturée ne peut plus être modifiée ni supprimée.
create or replace function public.pos_sessions_lock_closed()
returns trigger
language plpgsql
as $$
begin
  if old.status = 'closed' then
    raise exception 'Session de caisse clôturée : modification interdite';
  end if;
  return case when tg_op = 'DELETE' then old else new end;
end;
$$;

drop trigger if exists pos_sessions_lock_closed on public.pos_sessions;
create trigger pos_sessions_lock_closed
  before update or delete on public.pos_sessions
  for each row execute function public.pos_sessions_lock_closed();

-- ── 3. Mouvements d'espèces ────────────────────────────────────────────────
create table if not exists public.pos_cash_movements (
  id          uuid primary key default gen_random_uuid(),
  session_id  uuid not null references public.pos_sessions(id),
  type        text not null check (type in ('in', 'out')),
  amount      numeric(12,2) not null check (amount > 0),
  reason      text not null check (length(btrim(reason)) > 0),
  created_by  uuid references public.profiles(id),
  created_at  timestamptz not null default now()
);

create index if not exists pos_cash_movements_session_idx
  on public.pos_cash_movements (session_id, created_at);

-- ── 4. Remboursements en boutique ──────────────────────────────────────────
create table if not exists public.pos_refunds (
  id                uuid primary key default gen_random_uuid(),
  client_refund_id  uuid unique,
  session_id        uuid references public.pos_sessions(id),
  order_id          uuid not null references public.orders(id),
  refund_id         uuid references public.refunds(id),
  method            text not null check (method in ('cash', 'card')),
  amount            numeric(12,2) not null check (amount > 0),
  items             jsonb not null default '[]'::jsonb,
  reason            text,
  stripe_refund_id  text,
  created_by        uuid references public.profiles(id),
  created_at        timestamptz not null default now()
);

create index if not exists pos_refunds_session_idx on public.pos_refunds (session_id, created_at);
create index if not exists pos_refunds_order_idx on public.pos_refunds (order_id);

-- Mouvements et remboursements uniquement sur une session ouverte.
create or replace function public.pos_assert_session_open()
returns trigger
language plpgsql
as $$
begin
  if new.session_id is not null and not exists (
    select 1 from public.pos_sessions where id = new.session_id and status = 'open'
  ) then
    raise exception 'Session de caisse fermée ou introuvable';
  end if;
  return new;
end;
$$;

drop trigger if exists pos_cash_movements_session_open on public.pos_cash_movements;
create trigger pos_cash_movements_session_open
  before insert on public.pos_cash_movements
  for each row execute function public.pos_assert_session_open();

drop trigger if exists pos_refunds_session_open on public.pos_refunds;
create trigger pos_refunds_session_open
  before insert on public.pos_refunds
  for each row execute function public.pos_assert_session_open();

-- Accès réservé au backend (service role).
alter table public.pos_registers      enable row level security;
alter table public.pos_sessions       enable row level security;
alter table public.pos_cash_movements enable row level security;
alter table public.pos_refunds        enable row level security;

-- ── 5. Remboursement / retour atomique ─────────────────────────────────────
-- Dans une seule transaction :
--   • contrôle des montants et des quantités déjà remboursés / retournés ;
--   • order_item_returns (+ remise en stock éventuelle, inventaire aligné) ;
--   • refunds (même table que les remboursements Stripe : le webhook
--     retrouve la ligne par stripe_refund_id, sans doublon) ;
--   • pos_refunds (rattachement à la session de caisse) ;
--   • commande « refunded » si le remboursement est intégral.
-- Idempotent : un même p_client_refund_id renvoie le résultat existant.
create or replace function public.pos_record_refund(
  p_client_refund_id uuid,
  p_order_id         uuid,
  p_session_id       uuid,
  p_method           text,
  p_amount           numeric,
  p_items            jsonb,
  p_reason           text,
  p_created_by       uuid,
  p_stripe_refund_id text default null,
  p_stripe_status    text default null
)
returns jsonb
language plpgsql
security definer
set search_path to 'public', 'pg_temp'
as $function$
declare
  v_existing   public.pos_refunds%rowtype;
  v_order      public.orders%rowtype;
  v_oi         public.order_items%rowtype;
  v_item       record;
  v_returned   integer;
  v_refunded   numeric;
  v_payment_id uuid;
  v_refund_id  uuid;
  v_pos_id     uuid;
  v_total_ref  numeric;
  v_full       boolean := false;
begin
  if p_client_refund_id is null then
    raise exception 'Identifiant de remboursement manquant';
  end if;

  select * into v_existing from public.pos_refunds where client_refund_id = p_client_refund_id;
  if found then
    return jsonb_build_object(
      'pos_refund_id', v_existing.id,
      'refund_id', v_existing.refund_id,
      'duplicate', true
    );
  end if;

  select * into v_order from public.orders where id = p_order_id for update;
  if not found then
    raise exception 'Commande introuvable';
  end if;

  if v_order.status::text not in ('paid', 'processing', 'shipped', 'delivered') then
    raise exception 'Commande non remboursable (statut : %)', v_order.status;
  end if;

  if p_method not in ('cash', 'card') then
    raise exception 'Mode de remboursement invalide';
  end if;

  if p_method = 'cash' and p_session_id is null then
    raise exception 'Une session de caisse ouverte est requise pour rembourser en espèces';
  end if;

  if p_amount is null or p_amount <= 0 then
    raise exception 'Montant de remboursement invalide';
  end if;

  -- Remboursements déjà enregistrés (hors ligne Stripe déjà synchronisée
  -- par le webhook pour ce même remboursement).
  select coalesce(sum(amount), 0) into v_refunded
    from public.refunds
   where order_id = p_order_id
     and coalesce(status, 'succeeded') in ('succeeded', 'pending')
     and (p_stripe_refund_id is null or stripe_refund_id is distinct from p_stripe_refund_id);

  if v_refunded + p_amount > coalesce(v_order.total, 0) + 0.001 then
    raise exception 'Montant supérieur au solde remboursable (% CHF)',
      greatest(coalesce(v_order.total, 0) - v_refunded, 0);
  end if;

  -- Articles retournés
  for v_item in
    select (x->>'order_item_id')::uuid as order_item_id,
           (x->>'quantity')::integer   as quantity,
           coalesce((x->>'restock')::boolean, true) as restock
      from jsonb_array_elements(coalesce(p_items, '[]'::jsonb)) x
  loop
    if v_item.quantity is null or v_item.quantity <= 0 then
      raise exception 'Quantité retournée invalide';
    end if;

    select * into v_oi
      from public.order_items
     where id = v_item.order_item_id and order_id = p_order_id;
    if not found then
      raise exception 'Article introuvable dans cette commande';
    end if;

    select coalesce(sum(quantity), 0) into v_returned
      from public.order_item_returns
     where order_item_id = v_oi.id;

    if v_returned + v_item.quantity > v_oi.quantity then
      raise exception 'Quantité retournée supérieure à la quantité vendue (%)', v_oi.product_title;
    end if;

    insert into public.order_item_returns (order_id, order_item_id, quantity, restocked, reason)
    values (p_order_id, v_oi.id, v_item.quantity, v_item.restock, p_reason);

    if v_item.restock and v_oi.variant_id is not null then
      update public.product_variants
         set stock = stock + v_item.quantity,
             available = true,
             updated_at = now()
       where id = v_oi.variant_id;

      -- inventory_levels aligné sur product_variants.stock
      perform public.sync_variant_inventory(v_oi.variant_id);
    end if;
  end loop;

  select id into v_payment_id
    from public.payments
   where order_id = p_order_id
   order by created_at
   limit 1;

  if p_stripe_refund_id is not null then
    select id into v_refund_id from public.refunds where stripe_refund_id = p_stripe_refund_id;
  end if;

  if v_refund_id is null then
    insert into public.refunds (order_id, payment_id, amount, reason, stripe_refund_id, status, currency, created_at)
    values (
      p_order_id,
      v_payment_id,
      p_amount,
      coalesce(nullif(btrim(p_reason), ''), 'Remboursement en boutique'),
      p_stripe_refund_id,
      coalesce(p_stripe_status, 'succeeded'),
      upper(coalesce(v_order.currency, 'CHF')),
      now()
    )
    returning id into v_refund_id;
  else
    update public.refunds
       set reason = coalesce(nullif(btrim(p_reason), ''), reason)
     where id = v_refund_id;
  end if;

  insert into public.pos_refunds (
    client_refund_id, session_id, order_id, refund_id, method, amount,
    items, reason, stripe_refund_id, created_by
  )
  values (
    p_client_refund_id, p_session_id, p_order_id, v_refund_id, p_method, p_amount,
    coalesce(p_items, '[]'::jsonb), p_reason, p_stripe_refund_id, p_created_by
  )
  returning id into v_pos_id;

  select coalesce(sum(amount), 0) into v_total_ref
    from public.refunds
   where order_id = p_order_id
     and coalesce(status, 'succeeded') in ('succeeded', 'pending');

  if v_total_ref >= coalesce(v_order.total, 0) - 0.001 then
    v_full := true;
    update public.orders
       set status = 'refunded',
           refunded_at = now(),
           updated_at = now()
     where id = p_order_id;
  end if;

  return jsonb_build_object(
    'pos_refund_id', v_pos_id,
    'refund_id', v_refund_id,
    'refunded_total', v_total_ref,
    'full', v_full,
    'duplicate', false
  );
end;
$function$;

revoke all on function public.pos_record_refund(uuid, uuid, uuid, text, numeric, jsonb, text, uuid, text, text)
  from public, anon, authenticated;
grant execute on function public.pos_record_refund(uuid, uuid, uuid, text, numeric, jsonb, text, uuid, text, text)
  to service_role;
